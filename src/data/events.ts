import type { AuthorId, EventLogItem, Notification } from '../store/types';
import { daysAgo, hoursAgo, minutesAgo } from './time';

const d = daysAgo;

/** «10.10» для n дней назад */
function dm(n: number): string {
  const x = new Date(daysAgo(n));
  return `${String(x.getDate()).padStart(2, '0')}.${String(x.getMonth() + 1).padStart(2, '0')}`;
}

type Obj = EventLogItem['object'];
const raw: Omit<EventLogItem, 'id'>[] = [];

function ev(at: string, authorId: AuthorId, object: Obj, objectName: string, event: string, before?: string, after?: string) {
  const item: Omit<EventLogItem, 'id'> = { at, authorId, object, objectName, event };
  if (before !== undefined) item.before = before;
  if (after !== undefined) item.after = after;
  raw.push(item);
}

/** Цепочка переносов срока задачи: каждый вечер на день вперёд */
function chain(task: string, authorId: AuthorId, days: number[]) {
  for (const n of days) ev(d(n, 18, 50), authorId, 'Задача', task, 'Срок изменён', dm(n), dm(n - 1));
}

