export interface Ctx {
  client: string;
  first: string;
  clientFemale: boolean;
  sum: string;
  sum3: string;
  sumOld: string;
  other: string;
  ch: string;
  mgr: string;
  mgrFirst: string;
  src: string;
  fl: string;
  holiday: string;
  n: number;
  N: number;
}

/** Подставляет значения и родовые формы автора */
export function fill(text: string, ctx: Partial<Ctx>, female: boolean): string {
  let out = text.replace(/\{(client|first|sum3|sumOld|sum|other|ch|mgrFirst|mgr|src|fl|holiday|n|N)\}/g, (_, k: keyof Ctx) =>
    String(ctx[k] ?? ''),
  );
  out = out.replace(/\{([^{}|]*)\|([^{}|]*)\}/g, (_, m: string, f: string) => (female ? f : m));
  out = out.replace(/\{а\}/g, female ? 'а' : '');
  return out;
}

