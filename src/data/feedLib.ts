// Библиотека реплик для ленты сделок: цикл сделки по этапам и типовые косяки менеджеров.
// Плейсхолдеры: {client} {first} {sum} {sum3} {sumOld} {other} {ch} {mgr} {mgrFirst} {n} {N} {holiday} {src} {fl}
// Родовые формы относятся к автору записи: {а} → «»/«а», {x|y} → мужская/женская форма.

import type { FeedKind } from '../store/types';

export type Meta = Record<string, string | number | boolean>;
/** r — безответственный по сделке, boss — Перезвонов, sogl — Согласуев */
export type Who = 'r' | 'client' | 'robot' | 'boss' | 'sogl' | 'you';
/** [вид, автор, текст, минут от начала сцены, meta] */
export type BI = [FeedKind, Who, string, number?, Meta?];
export interface Beat {
  items: BI[];
  /** время суток, если сцена привязана к часам */
  clock?: [number, number];
  /** минимальная длительность этапа в днях, чтобы сцена не противоречила датам */
  min?: number;
}

export function mulberry32(seed: number) {
  let a = seed;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

