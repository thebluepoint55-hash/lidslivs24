const norm = (s: string) => ` ${s.toLowerCase().replace(/ё/g, 'е')}`;
const has = (text: string, stem: string) => {
  const t = norm(text);
  const st = stem.toLowerCase().replace(/ё/g, 'е');
  let i = t.indexOf(st);
  while (i !== -1) {
    if (!/[a-zа-я0-9]/.test(t[i - 1] ?? ' ')) return true;
    i = t.indexOf(st, i + 1);
  }
  return false;
};

let fallbackIdx = 0;
let introIdx = 0;

export function answer(question: string, ctx: Ctx): { text: string; copyable: boolean } {
  const intent = INTENTS.find((it) => it.stems.some((s) => has(question, s)));
  if (!intent) {
    const text = FALLBACK[fallbackIdx++ % FALLBACK.length];
    return { text, copyable: false };
  }
  const body = intent.answer(ctx);
  if (!intent.advice) return { text: body, copyable: intent.id === 'excuse' };
  const intro = INTRO[ctx.tone][introIdx++ % INTRO[ctx.tone].length];
  const outro = OUTRO[ctx.tone];
  return { text: [intro, '', body, ...(outro ? ['', outro] : [])].join('\n'), copyable: true };
}

