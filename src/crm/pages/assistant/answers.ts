/** Высокая «креативность» добавляет к отмазке убедительную деталь */
export function withFlair(text: string, creativity: number, seed = 0) {
  if (creativity < 70) return text;
  return `${text} ${FLAIR[Math.abs(seed) % FLAIR.length]}`;
}

